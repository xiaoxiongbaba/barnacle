const dictionaries: Record<Language, Record<Key, string>> = { en, ja, "zh-Hant": zhHant };

const STORAGE_KEY = "barnacle.lang";
let current: Language = "en";
const listeners = new Set<() => void>();

function stored(): Language | null {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return (LANGUAGES as readonly string[]).includes(v ?? "") ? (v as Language) : null;
  } catch {
    return null;
  }
}

/** Maps a browser language tag to one we support. Any Chinese variant gets Traditional Chinese for now. */
function fromBrowser(): Language | null {
  for (const tag of navigator.languages ?? [navigator.language]) {
    const lower = tag.toLowerCase();
    if (lower.startsWith("ja")) return "ja";
    if (lower.startsWith("zh")) return "zh-Hant";
    if (lower.startsWith("en")) return "en";
  }
  return null;
}

/** The viewer's own choice wins, then their browser, then the office default. */
export function initLanguage(officeDefault: string) {
  const fallback = (LANGUAGES as readonly string[]).includes(officeDefault) ? (officeDefault as Language) : "en";
  apply(stored() ?? fromBrowser() ?? fallback);
}

export function setLanguage(lang: Language) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Private mode or blocked storage: the choice just won't persist.
  }
  apply(lang);
}

function apply(lang: Language) {
  current = lang;
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll<HTMLElement>("[data-i18n]")) el.textContent = t(el.dataset.i18n as Key);
  for (const el of document.querySelectorAll<HTMLElement>("[data-i18n-placeholder]")) {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder as Key));
  }
  for (const el of document.querySelectorAll<HTMLElement>("[data-i18n-title]")) {
    el.setAttribute("title", t(el.dataset.i18nTitle as Key));
    el.setAttribute("aria-label", t(el.dataset.i18nTitle as Key));
  }
  for (const fn of listeners) fn();
}

export const language = () => current;

export function onLanguageChange(fn: () => void) {
  listeners.add(fn);
}

export function t(key: string, params: Record<string, string> = {}): string {
  const dict = dictionaries[current] as Record<string, string>;
  const text = dict[key] ?? (en as Record<string, string>)[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name: string) => params[name] ?? `{${name}}`);
}

/** Has this key been translated? Used to fall back to a pack's own labels for unknown areas. */
export const hasKey = (key: string) => key in en;

export const formatTime = (iso: string) =>
  new Date(iso).toLocaleTimeString(current, { hour: "2-digit", minute: "2-digit" });
